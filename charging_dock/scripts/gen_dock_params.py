"""Write case/dock_params.scad from geom.py + placement.py (dock frame: X right, Y back, Z up, origin front-left-bottom)."""
import os, geom as G, placement as PL, design
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../case/dock_params.scad")
L = ["// generated by scripts/gen_dock_params.py - do not edit (edit geom.py / placement.py)"]
def v(n, x): L.append(f"{n} = {x};")
for n in ("RL RT EDGE_R USB_FROM_END USB_FROM_FRONT MOUTH_UP GAP OUT_W OUT_D WALL CLR_GUIDE POCKET_WALL FIN_H FRONT_WALL_H FRONT_RETURN SIDE_NOTCH_D SIDE_NOTCH_Z CHAMFER "
          "BASE_T STANDOFF PCB_T PCB_Z0 PCB_Z1 PAD_T FLOOR_Z PLUG_H PLUG_TOP TOP_Z FIN_Z PCB_X0 PCB_Y0 PCB_X1 PCB_Y1").split():
    v(n, round(getattr(G, n), 4))
v("radios", [list(G.radio_box(c, r)[:2]) for (c, r) in G.SLOTS])
v("plugs", [[round(a, 3) for a in G.usb_xy(c, r)] for (c, r) in G.SLOTS])
v("holes", [[round(a, 3) for a in G.d(x, y)] for (x, y) in PL.HOLES])
v("pegs", [[round(a, 3) for a in G.d(x, y)] for (x, y) in PL.PEGS])
v("bucks", [[round(a, 3) for a in G.d(x, y)] for (x, y) in ((PL.XG1, PL.YF), (PL.XG2, PL.YF))])   # buck block centres (vents)
v("ychan_y", round(G.PCB_Y1 - PL.YC1, 3))
v("led_pipe", [round(a, 3) for a in G.d(*PL.LEDPIPE)])
jx, jy, _ = PL.PL["J1"]; v("usb_in", [round(a, 3) for a in G.d(jx, 0.0)])          # rear-edge centre of the input receptacle
v("usb_in_z", round(G.PCB_Z1 + 1.63, 3))
# raised housings over parts taller than the room under the deck: [cx, cy, w, d, part height]
HT = {"CP_Elec_8x10": (9.0, 10.7, 10.5), "CP_Elec_6.3x7.7": (6.8, 8.6, 7.9)}   # courtyard X x Y when rotated 90, body height
tall = []
for r in PL.TALL:
    fp = design.PARTS[r]["fp"]; w, d, h = next(val for k, val in HT.items() if k in fp)
    if PL.PL[r][2] % 180 == 0: w, d = d, w
    x, y = G.d(*PL.PL[r][:2]); tall.append([round(x, 3), round(y, 3), w, d, h])
v("tall", tall)
open(OUT, "w").write("\n".join(L) + "\n"); print("wrote", OUT)
