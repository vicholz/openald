"""Write case/case_params.scad from layout.py (mechanical layout). Everything in the case frame (see layout.py).
Direct-mount version: no controls PCB; the wheel, switch and optional LEDs mount straight into the printed parts."""
import os,sys
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
import layout as L
ROOT=os.path.dirname(HERE)
def v(x): return "[" + ", ".join(v(a) if isinstance(a,(list,tuple)) else ("%g"%a if isinstance(a,(int,float)) else '"%s"'%a) for a in x) + "]"
o=["// AUTO-GENERATED by scripts/gen_case_params.py from scripts/layout.py -- do not edit",
   "// case frame: X across (centre 19), Y=0 at the USB-C receptacle face, Z=0 at the Feather bottom face",
   "include <feather_params.scad>"]
def S(n,val): o.append(f"{n} = {val if isinstance(val,str) else ('%g'%val)};")
for n in ["WALL","CLR","EDGE_R","IN_X0","IN_X1","IN_R","OUT_R","Y_IN0","Y_OUT0","TOP_IN","TOP_T","BOT_OUT","USB_X","USB_Z","USB_W","USB_H",
          "DOCK_DEPTH","DOCK_LINE_Y","FLOOR_T","FLOOR_Z","J0","J1","WIDEN","IN_X0U","IN_X1U","Y_IN1","Y_OUT1","TOP_OUT_R","TOP_IN_R",
          "DECK_Z0","DECK_Z1","FM_HOLE_INSET","FM_HOLE_D","FM_JACK_X","FM_JACK_AXIS_H","FM_JACK_BODY_H","FM_JACK_HOLE_D",
          "WHEEL_R","WHEEL_SEAT_Z","WHEEL_PUSH","SW_L","SW_Y","SW_Z","SW_LUG_L","SW_LUG_P","SW_TRAVEL","SW_SKIN","SW_GROOVE","SW_RIB","SW_CRUSH","HOLDER_POCKET","DECK_RELIEF","LED3_ABOVE_FLANGE"]:
    S(n,getattr(L,n))
H=L.HOLDER; S("holder_box",v([H["x0"],H["x1"],H["y0"],H["y1"],H["z0"],H["z1"]]))
S("holder_pins",v([[p[0],p[1]] for p in L.HOLDER_PINS]))
F=L.FM; S("fm_box",v([F["x0"],F["x1"],F["y0"],F["y1"],F["z0"],F["t"]]))
S("wheel_xy",v(L.WHEEL)); S("wheel_z0",L.WHEEL_DIAL_Z[0]); S("wheel_z1",L.WHEEL_DIAL_Z[1])
S("sw_plate",v(L.SW_PLATE)); S("sw_body",v(L.SW_BODY)); S("sw_act",v(L.SW_ACT))
S("led3",v([[x,y] for (_c,_l,x,y) in L.LED3]))
S("screws",v([list(p) for p in L.SCREWS]))
S("frame_tabs",v([[ {"L":0,"R":1,"T":2}[t[0]], t[1], t[2]] for t in L.FRAME_TABS]))   # side 0=L 1=R 2=T
open(os.path.join(ROOT,"case","case_params.scad"),"w").write("\n".join(o)+"\n")
print("wrote case/case_params.scad")
