"""Write case/case_params.scad from layout.py (mechanical layout, case frame - see layout.py)."""
import os,sys
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
import layout as L
ROOT=os.path.dirname(HERE)
def v(x): return "[" + ", ".join(v(a) if isinstance(a,(list,tuple)) else ("%g"%round(a,4) if isinstance(a,(int,float)) else '"%s"'%a) for a in x) + "]"
o=["// AUTO-GENERATED by scripts/gen_case_params.py from scripts/layout.py -- do not edit",
   "// case frame: X across (0 = centre line, +X = right / wheel side), Y = 0 at the inner face of the bottom (USB-C) end wall, Z = 0 at the back face"]
def S(n,val): o.append(f"{n} = {val if isinstance(val,str) else ('%g'%round(val,4))};")
for n in ["T","L_OUT","WALL","EDGE_R","OUT_R","IN_R","USB_W","USB_H","USB_LEN","USB_RECESS_GAP","FLOOR_T","FRONT_T","IN_L","IN_W","W_OUT","IN_X0","IN_X1",
          "HOLDER_POCKET","F_T","F_Z0","F_Z1","F_STANDOFF","DECK_Z0","DECK_T","DECK_Z1","Z_SPLIT","Z_CEIL",
          "DOCK_USB_X","DOCK_USB_Z","DOCK_USB_MOUTH_Y","DOCK_USB_FROM_FRONT","FM_T","FM_HOLE_D","FM_JACK_D","FM_JACK_L","FM_JACK_OUT","FM_STANDOFF",
          "FM_CX","FM_CY","FM_JACK_AXIS_Z","FM_JACK_HOLE_D","WHEEL_R","WHEEL_SEAT_Z","WHEEL_PUSH","SW_L","SW_Y","SW_Z","SW_LUG_L","SW_LUG_P","SW_TRAVEL","SW_SKIN","SW_GROOVE","SW_RIB","HOLDER_CX",
          "F_POST_D","F_PEG_D"]:
    S(n,getattr(L,n))
S("USB_RECESS",v(L.USB_RECESS))
H=L.HOLDER; S("holder_box",v([H["x0"],H["x1"],H["y0"],H["y1"],H["z0"],H["z1"]]))
S("holder_pins",v([[p[0],p[1]] for p in L.HOLDER_PINS]))
F=L.FM; S("fm_box",v([F["x0"],F["x1"],F["y0"],F["y1"],F["z0"],F["z1"]]))
S("fm_holes",v([list(h) for h in L.FM_HOLES]))
S("fm_hdr",v([L.FM_HDR["w"],L.FM_HDR["d"],L.FM_HDR["below"],L.FM_HDR["y"]]))
S("wheel_xy",v(L.WHEEL)); S("wheel_z0",L.WHEEL_DIAL_Z[0]); S("wheel_z1",L.WHEEL_DIAL_Z[1]); S("wheel_body",v(L.WHEEL_BODY))
S("sw_plate",v(L.SW_PLATE)); S("sw_body",v(L.SW_BODY)); S("sw_act",v(L.SW_ACT))
fl=L.feather_leds()
S("f_leds",v([[fl[k][0],fl[k][1]]+list(L.LED_TUN[k]) for k in ("chg","red","neo")]))   # [x, y, bore d, wall, wall bottom above the Feather top]
S("f_reset",v(list(L.feather_reset())+list(L.RESET_TUBE)))
S("f_holes",v([list(h) for h in L.feather_holes()]))
fb=L.feather_boxes()
S("feather_board",v(fb[0][1])); S("feather_parts",v([b for n,b in fb[1:]]))
S("feather_usb",v(L.feather_usb()))
open(os.path.join(ROOT,"case","case_params.scad"),"w").write("\n".join(o)+"\n")
print("wrote case/case_params.scad")
