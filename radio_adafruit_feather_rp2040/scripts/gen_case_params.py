"""Write case/case_params.scad from layout.py (mechanical layout) and the routed controls board (THT pad / hole
positions for the frame reliefs). Everything in the case frame (see layout.py)."""
import os,sys,pcbnew
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
import layout as L
from build_pcb import PRJ,NAME,X0,Y1
ROOT=os.path.dirname(HERE)
b=pcbnew.LoadBoard(PRJ+NAME+".kicad_pcb")
def C(v): return (round(pcbnew.ToMM(v.x)-100+X0,3), round(Y1-(pcbnew.ToMM(v.y)-100),3))
tht=[]
for f in b.GetFootprints():
    for p in f.Pads():
        if p.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH,pcbnew.PAD_ATTRIB_NPTH) and p.GetDrillSize().x>0:
            if f.GetReference().startswith("H"): continue
            x,y=C(p.GetPosition()); s=p.GetSize(); d=max(pcbnew.ToMM(p.GetDrillSize().x),pcbnew.ToMM(p.GetDrillSize().y))
            tht.append((f.GetReference(),x,y,round(max(d+1.2,1.6),2)))
def v(x): return "[" + ", ".join(v(a) if isinstance(a,(list,tuple)) else ("%g"%a if isinstance(a,(int,float)) else '"%s"'%a) for a in x) + "]"
o=["// AUTO-GENERATED by scripts/gen_case_params.py from scripts/layout.py and the controls-board PCB -- do not edit",
   "// case frame: X across (centre 19), Y=0 at the USB-C receptacle face, Z=0 at the Feather bottom face",
   "include <feather_params.scad>"]
def S(n,val): o.append(f"{n} = {val if isinstance(val,str) else ('%g'%val)};")
for n in ["WALL","CLR","EDGE_R","IN_X0","IN_X1","IN_R","OUT_R","Y_IN0","Y_OUT0","TOP_IN","TOP_T","BOT_OUT","USB_X","USB_Z","USB_W","USB_H",
          "DOCK_DEPTH","DOCK_LINE_Y","FLOOR_T","FLOOR_Z","J0","J1","WIDEN","IN_X0U","IN_X1U","Y_IN1","Y_OUT1","TOP_OUT_R","TOP_IN_R",
          "DECK_Z0","DECK_Z1","FM_HOLE_INSET","FM_HOLE_D","FM_JACK_X","FM_JACK_AXIS_H","FM_JACK_BODY_H","FM_JACK_HOLE_D","CB_Z0","CB_T","CB_HOLE_D"]:
    S(n,getattr(L,n))
H=L.HOLDER; S("holder_box",v([H["x0"],H["x1"],H["y0"],H["y1"],H["z0"],H["z1"]]))
S("holder_pins",v([[p[0],p[1]] for p in L.HOLDER_PINS]))
F=L.FM; S("fm_box",v([F["x0"],F["x1"],F["y0"],F["y1"],F["z0"],F["t"]]))
S("cb_outline",v([list(p) for p in L.CB_OUTLINE])); S("cb_holes",v([list(p) for p in L.CB_HOLES]))
S("wheel_xy",v(L.WHEEL)); S("wheel_r",7.25); S("wheel_z0",2.0); S("wheel_z1",4.0)
S("sw_pin_x",L.SWITCH_PIN_X); S("sw_y",L.SWITCH_Y)
S("sw_off_y",L.SWITCH_Y-1.25); S("sw_on_y",L.SWITCH_Y+1.25)          # knob toward pin 1 (lower Y) = OFF
S("sw_tip_x",L.SWITCH_PIN_X+7.8); S("sw_face_x",L.SWITCH_PIN_X+2.8); S("sw_act_w",3.5); S("sw_act_z0",2.25); S("sw_act_z1",4.75); S("sw_body_h",6.0)
S("cb_leds",v([[x,y] for (_r,x,y,_c,_l) in L.LEDS]))
S("screws",v([list(p) for p in L.SCREWS]))
S("cb_tht",v([[x,y,d] for (_r,x,y,d) in tht]))
S("pad_col",v([L.PAD_X,L.PAD_Y0,L.PAD_Y0+(len(L.PADS)-1)*L.PAD_P]))
open(os.path.join(ROOT,"case","case_params.scad"),"w").write("\n".join(o)+"\n")
print("tht pads:",tht)
