#!/usr/bin/env python3
"""Read the routed PCB and write case/case_params.scad with every cutout position
derived from actual footprint placement.  Case frame: X = PCB x (mm from left edge),
Y = 85 - PCB y (so USB-C edge is Y=0, jack/top edge is Y=board_h), Z=0 = PCB bottom."""
import pcbnew, math, os
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
b=pcbnew.LoadBoard(os.path.join(ROOT,'kicad','openald.kicad_pcb'))
bb=b.GetBoardEdgesBoundingBox()
ox,oy=pcbnew.ToMM(bb.GetX()),pcbnew.ToMM(bb.GetY()); W,H=pcbnew.ToMM(bb.GetWidth()),pcbnew.ToMM(bb.GetHeight())
lw=max(pcbnew.ToMM(d.GetWidth()) for d in b.GetDrawings() if d.GetLayer()==pcbnew.Edge_Cuts)
ox+=lw/2; oy+=lw/2; W-=lw; H-=lw   # bbox includes outline stroke
fps={f.GetReference():f for f in b.GetFootprints()}
def tf(ref,lx=0,ly=0):
    """footprint-local point -> case XY"""
    f=fps[ref]; a=math.radians(f.GetOrientationDegrees())
    px,py=pcbnew.ToMM(f.GetPosition().x)-ox,pcbnew.ToMM(f.GetPosition().y)-oy
    # KiCad: positive rotation is CCW on screen (y down) -> x' = x cos + y sin, y' = -x sin + y cos
    gx=px+lx*math.cos(a)+ly*math.sin(a); gy=py-lx*math.sin(a)+ly*math.cos(a)
    return round(gx,3),round(H-gy,3)
def crt(ref,layer=pcbnew.F_CrtYd):
    xs=[];ys=[]
    for it in fps[ref].GraphicalItems():
        if it.GetLayer()==layer:
            r=it.GetBoundingBox(); xs+=[pcbnew.ToMM(r.GetLeft())-ox,pcbnew.ToMM(r.GetRight())-ox]; ys+=[pcbnew.ToMM(r.GetTop())-oy,pcbnew.ToMM(r.GetBottom())-oy]
    return min(xs),max(xs),min(ys),max(ys)
holes=[tf(r) for r in ('H1','H2','H3','H4')]
# clearance from each hole to nearest top-side courtyard (limits top boss diameter)
def mind(hx,hy,side):
    d=99
    for r,f in fps.items():
        if r.startswith('H'): continue
        if (side=='F')==f.IsFlipped(): continue
        try: x0,x1,y0,y1=crt(r,pcbnew.F_CrtYd if side=='F' else pcbnew.B_CrtYd)
        except ValueError: continue
        Y0,Y1=H-y1,H-y0
        dx=max(x0-hx,0,hx-x1); dy=max(Y0-hy,0,hy-Y1); d=min(d,math.hypot(dx,dy))
    return d
topclr=min(mind(x,y,'F') for x,y in holes); botclr=min(mind(x,y,'B') for x,y in holes)
jack=tf('J2',-8.4,0)          # mouth face centre (tube end) in local coords
wheel=tf('SW3')               # wheel centre
usb=tf('J1',0,0)
d3=tf('D3'); d4=tf('D4')
bar=[tf(r) for r in ('D1','D5','D6')]   # 3x 0603 level-bar LEDs (low -> full, bottom -> top, vertical column centred at x=19)
# OS102011MA1Q (KiCad footprint = C&K drawing): actuator 2x2 mm, sticks out 4.0 mm from the body face at
# local y=+2.2, spans local x 0..2 (pos.1, pins 1-2) or 2..4 (pos.2, pins 2-3 = ON); 1.6..3.6 mm above PCB
sw_on=tf('SW1',1.25,0); sw_off=tf('SW1',-1.25,0); sw_tip=tf('SW1',0,7.8); sw_face=tf('SW1',0,2.8)   # SK-12E12-G5: knob +-1.25 travel, 2.8..7.8 from pin line
btx=crt('BT1',pcbnew.B_CrtYd)
L=[]
def p(k,v): L.append(f"{k} = {v};")
L.append("// AUTO-GENERATED by scripts/gen_case_params.py from kicad/openald.kicad_pcb -- do not edit")
p("pcb_w",round(W,3)); p("pcb_h",round(H,3)); p("pcb_r",3.0); p("pcb_t",1.6)
p("holes",[list(h) for h in holes])
p("top_boss_room",round(topclr,2)); p("bot_boss_room",round(botclr,2))
p("jack_xy",list(jack)); p("jack_axis_h",2.5)          # PJ-320D datasheet: dia-5 barrel, body 5.0 tall
p("wheel_xy",list(wheel)); p("wheel_r",7.25); p("wheel_z0",2.0); p("wheel_z1",4.0)
import sys; sys.path.insert(0,HERE); import placement as _PL
barwin=[[tf(r)[0],round(H-_PL.BAR_WIN_Y[r],3)] for r in ('D1','D5','D6')]   # window centres (tunnel tops), case XY
p("bar_win_xy",barwin)
p("bar_leds",[list(q) for q in bar]); p("led_rot",[round(fps[r].GetOrientationDegrees()) for r in ('D1','D5','D6','D3','D4')])   # 0603 LEDs, 1.6 x 0.8 x 0.6 mm
p("sw_on_y",sw_on[1]); p("sw_off_y",sw_off[1]); p("sw_tip_x",sw_tip[0]); p("sw_face_x",sw_face[0])
p("sw_act_w",3.5); p("sw_act_z0",2.25); p("sw_act_z1",4.75); p("sw_body_h",6.0)
p("usb_xy",list(usb)); p("usb_w",8.94); p("usb_h",3.26)
p("chg_leds",[list(d3),list(d4)])
p("holder_box",[round(btx[0],2),round(btx[1],2),round(H-btx[3],2),round(H-btx[2],2)]); p("holder_h",21.31)
p("top_tallest",6.0)   # tallest top-side part = SK-12E12-G5 slide switch body
open(os.path.join(ROOT,'case','case_params.scad'),'w').write("\n".join(L)+"\n")
print("\n".join(L))
