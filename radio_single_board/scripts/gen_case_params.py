#!/usr/bin/env python3
"""Read the PCB and write case/case_params.scad with every cutout position derived from the actual footprint
placement.  Case frame (t116u bottom-end USB-C): X = PCB x (0 = left edge in the front view), Y = BOARD_H - PCB y
(Y = 0 at the BOTTOM / USB-C / dock end, Y = BOARD_H at the top / jack end), Z = 0 at the PCB bottom face."""
import pcbnew, math, os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
sys.path.insert(0,HERE); import placement as PL
b=pcbnew.LoadBoard(os.path.join(ROOT,'kicad','openald.kicad_pcb'))
bb=b.GetBoardEdgesBoundingBox()
ox,oy=pcbnew.ToMM(bb.GetX()),pcbnew.ToMM(bb.GetY()); W,H=pcbnew.ToMM(bb.GetWidth()),pcbnew.ToMM(bb.GetHeight())
lw=max(pcbnew.ToMM(d.GetWidth()) for d in b.GetDrawings() if d.GetLayer()==pcbnew.Edge_Cuts)
ox+=lw/2; oy+=lw/2; W-=lw; H-=lw   # bbox includes outline stroke
fps={f.GetReference():f for f in b.GetFootprints()}
def tf(ref,lx=0,ly=0):
    """footprint-local point -> case XY"""
    f=fps[ref]; a=math.radians(f.GetOrientationDegrees())
    px,py=pcbnew.ToMM(f.GetPosition().x)-ox,pcbnew.ToMM(f.GetPosition().y)-oy
    gx=px+lx*math.cos(a)+ly*math.sin(a); gy=py-lx*math.sin(a)+ly*math.cos(a)
    return round(gx,3),round(H-gy,3)
def crt(ref,layer=pcbnew.F_CrtYd):
    xs=[];ys=[]
    for it in fps[ref].GraphicalItems():
        if it.GetLayer()==layer:
            r=it.GetBoundingBox(); xs+=[pcbnew.ToMM(r.GetLeft())-ox,pcbnew.ToMM(r.GetRight())-ox]; ys+=[pcbnew.ToMM(r.GetTop())-oy,pcbnew.ToMM(r.GetBottom())-oy]
    return min(xs),max(xs),min(ys),max(ys)
screws=[[round(x,3),round(H-y,3)] for x,y in PL.BT1_NPTH]
# nearest top-side courtyard to each screw point (limits the front-shell boss radius)
def mind(hx,hy):
    d=99
    for r,f in fps.items():
        if f.IsFlipped(): continue
        try: x0,x1,y0,y1=crt(r)
        except ValueError: continue
        Y0,Y1=H-y1,H-y0
        dx=max(x0-hx,0,hx-x1); dy=max(Y0-hy,0,hy-Y1); d=min(d,math.hypot(dx,dy))
    return d
boss_room=min(mind(x,y) for x,y in screws)
# through-hole tails under the battery holder (holes in the 0.8 mm holder spacer)
btx=crt('BT1',pcbnew.B_CrtYd)
tails=[]
for f in b.GetFootprints():
    if f.GetReference() in ('BT1',) or f.IsDNP(): continue
    for pd in f.Pads():
        if pd.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH,pcbnew.PAD_ATTRIB_NPTH):
            x=pcbnew.ToMM(pd.GetPosition().x)-ox; y=pcbnew.ToMM(pd.GetPosition().y)-oy
            if btx[0]-1<x<btx[1]+1 and btx[2]-1<y<btx[3]+1:
                tails.append([round(x,2),round(H-y,2),round(max(pcbnew.ToMM(pd.GetSize().x),pcbnew.ToMM(pd.GetSize().y))+0.8,2)])
L=[]
def p(k,v): L.append(f"{k} = {v};")
L.append("// AUTO-GENERATED by scripts/gen_case_params.py from kicad/openald.kicad_pcb -- do not edit")
p("pcb_w",round(W,3)); p("pcb_h",round(H,3)); p("pcb_r",PL.CORNER_R); p("pcb_t",1.6)
p("screws",screws); p("boss_room",round(boss_room,2))
p("jack_xy",list(tf('J2',-8.4,0))); p("jack_axis_h",2.5)          # PJ-320D: dia-5 barrel, body 5.0 tall, mouth at the board edge
p("wheel_xy",list(tf('SW3'))); p("wheel_r",7.25); p("wheel_z0",2.0); p("wheel_z1",4.0)
p("bar_leds",[list(tf(r)) for r in ('D1','D5','D6')])     # 3 x 0603 level-bar LEDs in a column, D1 (lowest level) nearest the dock end
p("chg_leds",[list(tf(r)) for r in ('D3','D4')])
p("led_rot",[round(fps[r].GetOrientationDegrees()) for r in ('D1','D5','D6','D3','D4')])
sw_on=tf('SW1',1.25,0); sw_off=tf('SW1',-1.25,0); sw_tip=tf('SW1',0,7.8); sw_face=tf('SW1',0,2.8)   # SK-12E12-G5: knob +-1.25 travel, 2.8..7.8 from the pin line
p("sw_on_y",sw_on[1]); p("sw_off_y",sw_off[1]); p("sw_tip_x",sw_tip[0]); p("sw_face_x",sw_face[0])
p("sw_act_w",3.5); p("sw_act_z0",2.25); p("sw_act_z1",4.75); p("sw_body_h",6.0)
p("usb_x",round(PL.USB_X,3)); p("usb_mouth_y",-PL.USB_OVERHANG); p("usb_w",8.94); p("usb_h",3.26)
hx0=PL.BT1_PAD1[0]-20.9/2   # Keystone 1043 / BH-18650-PC body 77.7 x 20.9, 21.31 above the board (datasheet)
p("holder_box",[round(hx0,2),round(hx0+20.9,2),round(H-(PL.HOLDER_Y0+77.7),2),round(H-PL.HOLDER_Y0,2)]); p("holder_h",21.31)
p("holder_pins",[[PL.BT1_PAD1[0],round(H-PL.BT1_PAD1[1],3)],[PL.BT1_PAD2[0],round(H-PL.BT1_PAD2[1],3)]])
p("tails",tails)
p("top_tallest",6.0)   # tallest top-side part = SK-12E12-G5 slide switch body
open(os.path.join(ROOT,'case','case_params.scad'),'w').write("\n".join(L)+"\n")
print("\n".join(L))
